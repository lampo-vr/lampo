export function generatePassword(): string {
  const r = new Uint32Array(4);
  crypto.getRandomValues(r);
  const word = (i: number) => WORDS[r[i] % WORDS.length];
  return `${word(0)}-${word(1)}-${word(2)}-${10 + (r[3] % 90)}`;
}
